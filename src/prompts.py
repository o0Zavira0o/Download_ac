from __future__ import annotations

BASE_PROMPT_FA = """
این تصویر را الگوی اصلی قرار بده. آن را کامل کن، بهبود بده و یک والپیپر دیجیتال بسیار باکیفیت بساز.
جایی را تار نکن. همه جزئیات باید با بالاترین کیفیت، شارپنس مناسب، نورپردازی تمیز و بدون اعوجاج ترسیم شوند.
بخش های خالی یا ناقص را با ایده پردازی هماهنگ با تصویر اصلی کامل کن، اما سبک، موضوع، رنگ ها و حس کلی تصویر حفظ شود.
خروجی باید مناسب استفاده به عنوان والپیپر باشد، بدون متن اضافه، لوگو، واترمارک، قاب، حاشیه یا نوشته.
""".strip()


def build_prompt(orientation: str) -> str:
    orientation = orientation.lower().strip()
    if orientation == "portrait":
        fa = "خروجی را عمودی و مناسب تبلت بزرگ بساز. ترکیب بندی باید کاملا عمودی باشد."
    elif orientation == "landscape":
        fa = "خروجی را افقی و مناسب تبلت بزرگ بساز. ترکیب بندی باید کاملا افقی باشد."
    else:
        fa = "خروجی را مربعی، با ترکیب بندی متعادل و مناسب والپیپر بساز."
    return f"{BASE_PROMPT_FA}\n\n{fa}"
